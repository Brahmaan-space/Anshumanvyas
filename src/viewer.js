const btn = document.getElementById('play');
const bar = document.getElementById('bar');
const fill = document.getElementById('fill');
const chapEls = Array.from(document.querySelectorAll('.chap'));

function setPlaying(v) {
  playing = v && allowed && !reduce;
  btn.setAttribute('aria-label', playing ? 'Pause' : 'Play');
  btn.dataset.state = playing ? 'playing' : 'paused';
}

function paint() {
  fill.style.width = (time / DUR * 100).toFixed(2) + '%';
  bar.setAttribute('aria-valuenow', time.toFixed(1));
  let act = 0;
  for (let i = 0; i < ACTS.length; i++) if (time >= ACTS[i].t0) act = i;
  chapEls.forEach((c, i) => c.classList.toggle('on', i === act));
}

function seek(t) {
  time = MathUtils.clamp(t, 0, DUR);
  update(time);
  paint();
}

btn.addEventListener('click', () => {
  if (time >= DUR - 0.01) { seek(0); setPlaying(true); return; }
  setPlaying(!playing);
});
chapEls.forEach((c, i) => c.addEventListener('click', () => { seek(ACTS[i].t0 + 0.02); setPlaying(true); }));

function scrubFrom(e) {
  const r = bar.getBoundingClientRect();
  seek(clamp01((e.clientX - r.left) / r.width) * DUR);
}
let scrubbing = false;
bar.addEventListener('pointerdown', (e) => { scrubbing = true; bar.setPointerCapture(e.pointerId); scrubFrom(e); });
bar.addEventListener('pointermove', (e) => { if (scrubbing) scrubFrom(e); });
bar.addEventListener('pointerup', (e) => { scrubbing = false; try { bar.releasePointerCapture(e.pointerId); } catch (_) {} });
bar.addEventListener('keydown', (e) => {
  if (e.key === 'ArrowRight') { seek(time + 1); e.preventDefault(); }
  if (e.key === 'ArrowLeft') { seek(time - 1); e.preventDefault(); }
  if (e.key === ' ' || e.key === 'Enter') { setPlaying(!playing); e.preventDefault(); }
});

/* --------------------------------------------- visibility, in page and out */
// Inside an iframe an IntersectionObserver only sees the iframe's own viewport,
// so the parent tells us when the embed is actually on screen. Standalone, no
// message ever arrives and we simply play.
let heardFromParent = false;
window.addEventListener('message', (e) => {
  if (!e.data || e.data.type !== 'viewer-visibility') return;
  heardFromParent = true;
  allowed = !!e.data.visible;
  if (!allowed) setPlaying(false);
  else if (time < DUR - 0.01) setPlaying(true);
});

document.addEventListener('visibilitychange', () => {
  if (document.hidden) setPlaying(false);
  else if (allowed && time < DUR - 0.01) setPlaying(true);
});

/* -------------------------------------------------------------------- loop */
function frame(now) {
  requestAnimationFrame(frame);
  const dt = Math.min((now - last) / 1000, 0.05);
  last = now;
  if (playing) {
    time += dt;
    if (time >= DUR) { time = DUR; setPlaying(false); }
    update(time);
    paint();
  }
  renderer.render(scene, camera);
}

resize();
update(0);
paint();
setPlaying(false);
requestAnimationFrame((n) => { last = n; frame(n); });

if (reduce) {
  seek(ACTS[2].t0 + 8);
  document.getElementById('shell').classList.add('static');
} else {
  setTimeout(() => { if (!heardFromParent) { allowed = true; setPlaying(true); } }, 800);
}

window.__viewer = { seek, resize, get time() { return time; }, get playing() { return playing; }, DUR, ACTS };
