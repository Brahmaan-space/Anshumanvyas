/* Mission viewer for the L1 project page.
 *
 * Three acts, each rendered in its own unit system because the scales involved
 * span five orders of magnitude (a 6,600 km perigee up to 1.5e8 km to the Sun).
 * Holding all of that in one coordinate system wrecks depth precision, so each
 * act gets a comfortable scale and the handovers hide behind a cross-fade timed
 * to land when Earth is about the same apparent size in both.
 *
 * The camera is framing-driven rather than position-driven: every act says how
 * many world units it needs to see and the distance falls out of the field of
 * view and the aspect ratio. That keeps the subject filling the frame at any
 * window size, which hand-tuned camera distances never manage.
 *
 * Every path drawn here is real. src/mission-data.json is generated by
 * tools/compute_mission.py from the same orbits, Lambert arc and corrected halo
 * the writeup describes. Nothing is drawn freehand.
 */

