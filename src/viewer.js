/** Camera distance at which a sphere of this radius just fills the frame. */
function fitDistance(radius) {
  const tv = Math.tan(MathUtils.degToRad(camera.fov) / 2);
  return radius / Math.min(tv, tv * camera.aspect);
}

/* --------------------------------------------------------------- utilities */
function polyline(pts, scale, color, opacity) {
  const g = new BufferGeometry();
  const a = new Float32Array(pts.length * 3);
  for (let i = 0; i < pts.length; i++) {
    a[i * 3] = pts[i][0] / scale;
    a[i * 3 + 1] = pts[i][1] / scale;
    a[i * 3 + 2] = pts[i][2] / scale;
  }
  g.setAttribute('position', new BufferAttribute(a, 3));
  const line = new Line(g, new LineBasicMaterial({ color, transparent: true, opacity }));
  line.frustumCulled = false;
  return line;
}

/** Cumulative arc length along a polyline, for speed warping. */
function arcTable(pts, scale) {
  const cum = [0];
  for (let i = 1; i < pts.length; i++) {
    cum.push(cum[i - 1] + Math.hypot(
      (pts[i][0] - pts[i - 1][0]) / scale,
      (pts[i][1] - pts[i - 1][1]) / scale,
      (pts[i][2] - pts[i - 1][2]) / scale));
  }
  return { cum, L: cum[cum.length - 1] };
}

/** Fractional index at an absolute arc length along the polyline. */
function fracIndexAtLength(tab, L) {
  const target = MathUtils.clamp(L, 0, tab.L);
  let lo = 0, hi = tab.cum.length - 1;
  while (lo < hi) { const mid = (lo + hi) >> 1; if (tab.cum[mid] < target) lo = mid + 1; else hi = mid; }
  if (lo === 0) return 0;
  const a = tab.cum[lo - 1], b = tab.cum[lo];
  return (lo - 1) + (b > a ? (target - a) / (b - a) : 0);
}

/** Overwrite one vertex of a drawn polyline with an interpolated source point.
 *
 * A draw range can only start and end on whole vertices, so a moving window
 * over a coarse polyline makes both ends jump a full sample at a time -- on the
 * transfer arc that is 680,000 km per step, most of the frame early in the
 * cruise, and it reads as the line juddering. Writing the two end vertices
 * explicitly each frame pins them to exactly where they belong. The buffer is
 * rewritten from the source data every frame, so clobbering a vertex is safe.
 */
function pinVertex(line, pts, scale, vertexIndex, sourceIndex) {
  const p = at(pts, scale, sourceIndex);
  const a = line.geometry.getAttribute('position');
  a.setXYZ(vertexIndex, p.x, p.y, p.z);
  a.needsUpdate = true;
}

/** Draw a window of a polyline, with both ends landing exactly where asked. */
function drawWindow(line, pts, tab, scale, headIdx, trailLen) {
  const headLen = tab.cum[MathUtils.clamp(Math.floor(headIdx), 0, tab.cum.length - 1)];
  const fromF = fracIndexAtLength(tab, headLen - trailLen);
  const from = Math.floor(fromF);
  const to = Math.min(Math.ceil(headIdx), pts.length - 1);
  if (to <= from) { line.geometry.setDrawRange(0, 0); return; }
  pinVertex(line, pts, scale, from, fromF);
  pinVertex(line, pts, scale, to, headIdx);
  line.geometry.setDrawRange(from, to - from + 1);
}

/** Index at a given fraction of total arc length (binary search). */
function indexAtArc(tab, u) {
  const target = u * tab.L;
  let lo = 0, hi = tab.cum.length - 1;
  while (lo < hi) { const mid = (lo + hi) >> 1; if (tab.cum[mid] < target) lo = mid + 1; else hi = mid; }
  return lo;
}

/** Fractional index at normalised time u, from the stored timestamps. */
function indexAtTime(tn, u) {
  let lo = 0, hi = tn.length - 1;
  while (lo < hi) { const mid = (lo + hi) >> 1; if (tn[mid] < u) lo = mid + 1; else hi = mid; }
  if (lo === 0) return 0;
  const a = tn[lo - 1], b = tn[lo];
  return (lo - 1) + (b > a ? (u - a) / (b - a) : 0);
}

// These orbits are extremely eccentric: the last one runs from a 6,613 km
// perigee out to 128,351 km, and the craft covers half its orbit in a sliver of
// the period. Animated at the physically correct speed it crosses perigee
// between two frames, which reads as a glitch rather than as speed. The index
// is therefore blended toward constant screen speed: perigee stays visibly the
// fast part, but it happens over frames a viewer can follow.
const SPEED_BLEND = 0.75;
function warpedIndex(tn, tab, u) {
  return MathUtils.lerp(indexAtTime(tn, u), indexAtArc(tab, u), SPEED_BLEND);
}

function at(pts, scale, i) {
  // Interpolated, not rounded. Snapping to the nearest sample makes the craft
  // advance in visible steps whenever the polyline is coarse relative to the
  // frame, which it is at the start of the heliocentric leg.
  const c = MathUtils.clamp(i, 0, pts.length - 1);
  const k = Math.floor(c), f = c - k, k2 = Math.min(k + 1, pts.length - 1);
  return new Vector3(
    MathUtils.lerp(pts[k][0], pts[k2][0], f) / scale,
    MathUtils.lerp(pts[k][1], pts[k2][1], f) / scale,
    MathUtils.lerp(pts[k][2], pts[k2][2], f) / scale
  );
}

/** Soft round dot, used for every marker and glow. */
const DOT = (() => {
  const c = document.createElement('canvas');
  c.width = c.height = 64;
  const g = c.getContext('2d').createRadialGradient(32, 32, 0, 32, 32, 32);
  g.addColorStop(0, 'rgba(255,255,255,1)');
  g.addColorStop(0.35, 'rgba(255,255,255,0.85)');
  g.addColorStop(1, 'rgba(255,255,255,0)');
  const ctx = c.getContext('2d');
  ctx.fillStyle = g;
  ctx.fillRect(0, 0, 64, 64);
  return new CanvasTexture(c);
})();

/** A marker that keeps the same size on screen no matter how far the camera is. */
function dot(color, size, opacity = 1, additive = false) {
  const s = new Sprite(new SpriteMaterial({
    map: DOT, color, transparent: true, opacity,
    sizeAttenuation: false, depthWrite: false,
    blending: additive ? AdditiveBlending : undefined
  }));
  s.scale.setScalar(size);
  s.userData.size = size;
  return s;
}

function ball(r, color, opacity = 1) {
  return new Mesh(new SphereGeometry(r, 24, 16),
    new MeshBasicMaterial({ color, transparent: true, opacity }));
}

function wireGlobe(r, color, opacity) {
  const pos = [];
  const push = (a, b) => { pos.push(a.x, a.y, a.z, b.x, b.y, b.z); };
  for (let k = -2; k <= 2; k++) {
    const lat = (k / 3) * Math.PI / 2, rr = r * Math.cos(lat), yy = r * Math.sin(lat);
    let prev = null;
    for (let i = 0; i <= 48; i++) {
      const a = (i / 48) * Math.PI * 2;
      const p = new Vector3(rr * Math.cos(a), yy, rr * Math.sin(a));
      if (prev) push(prev, p);
      prev = p;
    }
  }
  for (let j = 0; j < 6; j++) {
    const lon = (j / 6) * Math.PI;
    let prev = null;
    for (let i = 0; i <= 48; i++) {
      const a = (i / 48) * Math.PI * 2;
      const p = new Vector3(r * Math.cos(a) * Math.cos(lon), r * Math.sin(a), r * Math.cos(a) * Math.sin(lon));
      if (prev) push(prev, p);
      prev = p;
    }
  }
  const g = new BufferGeometry();
  g.setAttribute('position', new Float32BufferAttribute(pos, 3));
  return new LineSegments(g, new LineBasicMaterial({ color, transparent: true, opacity }));
}

function markBase(group) {
  group.traverse((c) => { if (c.material) { c.material.transparent = true; c.userData.base = c.material.opacity; } });
}
function setFade(group, o) {
  group.visible = o > 0.001;
  if (!group.visible) return;
  group.traverse((c) => { if (c.material && c.userData.base !== undefined) c.material.opacity = c.userData.base * o; });
}

